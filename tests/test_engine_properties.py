"""Property tests for the invariants the design document states as rules.

Example-based tests pin the cases someone thought of. These state the invariants
and let Hypothesis search the input space, each mapped to the clause it protects:

* the 3.1 look-ahead rule - no bar is observable before it is available;
* the 10.3 replay rule - appending later sessions cannot change an earlier view;
* the 5 budget rule - merging targets never exceeds the budgets that fund them.

Valid inputs are generated by construction rather than filtered with skipTest: a
property that has to skip most of its inputs proves very little.
"""
from __future__ import annotations

from datetime import date, datetime, timezone
import math
from pathlib import Path
import sys
import unittest

PROJECT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT))

try:
    from hypothesis import HealthCheck, given, settings, strategies as st
except ImportError as exc:  # pragma: no cover - environment dependent
    st = None
    SKIP_REASON = "optional test dependency unavailable: " + str(exc)
else:
    SKIP_REASON = ""

from hybrid_quant.models import DailyBar, DataSnapshot, StrategyTarget  # noqa: E402
from hybrid_quant.portfolio import merge_targets  # noqa: E402

UTC = timezone.utc
EPSILON = 1e-9
QUIET = dict(max_examples=100, deadline=None, suppress_health_check=[HealthCheck.too_slow])


def bar(symbol: str, day: date, available_at: datetime) -> DailyBar:
    """A bar with valid OHLC, carrying only the fields these properties need."""
    return DailyBar(symbol=symbol, trade_date=day, open=10.0, high=11.0, low=9.0,
                    close=10.5, turnover=1000.0, available_at=available_at)


def snapshot(decision_at: datetime, histories: dict) -> DataSnapshot:
    return DataSnapshot(decision_at=decision_at, securities={}, histories=histories)


def days() -> "st.SearchStrategy":
    return st.dates(min_value=date(2018, 1, 1), max_value=date(2021, 12, 31))


def timestamps() -> "st.SearchStrategy":
    return st.datetimes(min_value=datetime(2017, 1, 1), max_value=datetime(2023, 1, 1),
                        timezones=st.just(UTC))


def rows(max_size: int, min_size: int = 0) -> "st.SearchStrategy":
    return st.lists(st.tuples(days(), timestamps()), min_size=min_size, max_size=max_size,
                    unique_by=lambda pair: pair[0])


# Budgets of at most 0.33 each over at most three sleeves stay inside account
# equity by construction; holdings of at most 0.2 each fit inside one sleeve.
def budgets() -> "st.SearchStrategy":
    return st.dictionaries(st.sampled_from(["stock", "etf", "defensive"]),
                           st.floats(min_value=0, max_value=0.33, allow_nan=False),
                           min_size=1, max_size=3)


def holdings() -> "st.SearchStrategy":
    return st.dictionaries(st.sampled_from(["A", "B", "C", "D"]),
                           st.floats(min_value=0, max_value=0.2, allow_nan=False),
                           max_size=4)


@unittest.skipUnless(st is not None, SKIP_REASON)
class LookAheadProperties(unittest.TestCase):
    @settings(**QUIET)
    @given(decision_at=timestamps(), entries=rows(6))
    def test_no_bar_is_observable_before_it_is_available(self, decision_at, entries):
        """3.1: bars are read as of the decision moment, never before availability."""
        history = tuple(bar("A", day, available) for day, available in sorted(entries))
        known = snapshot(decision_at, {"A": history}).known_history("A")
        for item in known:
            self.assertLessEqual(item.available_at, decision_at)
            self.assertLessEqual(item.trade_date, decision_at.date())
        expected = tuple(item for item in history
                         if item.available_at <= decision_at and item.trade_date <= decision_at.date())
        self.assertEqual(known, expected)

    @settings(**QUIET)
    @given(decision_at=timestamps(), entries=rows(5), extra=rows(3, min_size=1))
    def test_appending_later_sessions_cannot_change_an_earlier_view(self, decision_at, entries, extra):
        """10.3: future sessions must not rewrite what an earlier replay saw."""
        base = sorted(entries)
        taken = {day for day, _ in base}
        future = sorted(pair for pair in extra
                        if pair[0] > decision_at.date() and pair[0] not in taken)
        short = tuple(bar("A", day, available) for day, available in base)
        long = tuple(sorted(short + tuple(bar("A", day, available) for day, available in future),
                            key=lambda item: item.trade_date))
        self.assertEqual(snapshot(decision_at, {"A": short}).known_history("A"),
                         snapshot(decision_at, {"A": long}).known_history("A"))


@unittest.skipUnless(st is not None, SKIP_REASON)
class BudgetProperties(unittest.TestCase):
    @settings(**QUIET)
    @given(budget_vector=budgets(), sleeves=holdings())
    def test_merging_never_exceeds_the_budgets_that_fund_it(self, budget_vector, sleeves):
        """5: strategy budgets are fixed; unspent weight stays in cash."""
        now = datetime(2021, 6, 30, tzinfo=UTC)
        targets = tuple(StrategyTarget(name, now, dict(sleeves), ()) for name in sorted(budget_vector))
        merged = merge_targets(targets, budget_vector, now)
        self.assertLessEqual(math.fsum(merged.values()), math.fsum(budget_vector.values()) + EPSILON)
        self.assertLessEqual(math.fsum(merged.values()), 1 + EPSILON)
        for weight in merged.values():
            self.assertGreaterEqual(weight, 0.0)

    @settings(**QUIET)
    @given(budget_vector=budgets(), sleeves=holdings())
    def test_merge_is_independent_of_target_order(self, budget_vector, sleeves):
        """5: merging is a weighted sum, so the input order cannot matter."""
        now = datetime(2021, 6, 30, tzinfo=UTC)
        forward = tuple(StrategyTarget(name, now, dict(sleeves), ()) for name in sorted(budget_vector))
        self.assertEqual(merge_targets(forward, budget_vector, now),
                         merge_targets(tuple(reversed(forward)), budget_vector, now))


if __name__ == "__main__":
    unittest.main()
